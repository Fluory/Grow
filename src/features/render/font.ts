export const GLYPH_HEIGHT = 7;

function normalise(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[–—−]/g, '-')
    .replace(/[‘’`´]/g, "'")
    .replace(/ß/g, 'SS')
    .toUpperCase();
}

function glyph(char: string): readonly string[] {
  return GLYPHS[char] ?? (GLYPHS['?'] as readonly string[]);
}

/** Width in font pixels, including one pixel of spacing between glyphs. */
export function textWidth(text: string): number {
  const chars = [...normalise(text)];
  return chars.reduce((w, c) => w + (glyph(c)[0]?.length ?? 3) + 1, 0) - (chars.length > 0 ? 1 : 0);
}

/** Calls `plot(x, y)` for every lit pixel of `text` starting at (0, 0). */
export function rasterText(text: string, plot: (x: number, y: number) => void): void {
  let cursor = 0;
  for (const c of normalise(text)) {
    const g = glyph(c);
    g.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') plot(cursor + x, y);
    });
    cursor += (g[0]?.length ?? 3) + 1;
  }
}

/** Break text into lines that fit `maxWidth` font pixels, ending with "…" when truncated. */
export function wrapText(text: string, maxWidth: number, maxLines: number): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let line = '';
  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (textWidth(next) <= maxWidth) {
      line = next;
      continue;
    }
    if (line) lines.push(line);
    line = word;
    if (lines.length === maxLines) break;
  }
  if (line && lines.length < maxLines) lines.push(line);
  if (lines.length === maxLines && words.join(' ') !== lines.join(' ')) {
    let last = lines[maxLines - 1] ?? '';
    while (last.length > 1 && textWidth(`${last}...`) > maxWidth) last = last.slice(0, -1).trimEnd();
    lines[maxLines - 1] = `${last}...`;
  }
  return lines;
}
